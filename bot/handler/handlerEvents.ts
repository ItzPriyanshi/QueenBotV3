				if (typeof key !== "string")
					continue;
				const command = getCommandFromMap(GoatBot.commands, key) || getCommandFromMap(GoatBot.eventCommands, key);
				if (!command || typeof command.onAnyEvent !== "function")
					continue;
				const commandName = command.config.name;
